#!/usr/bin/env node
// Builds supabase/functions/push/index.ts (one self-contained file to paste into the Supabase editor)
// from template.ts by inlining js/messages.js, js/reminders.js and js/push-logic.js.
//   node tools/build-push.mjs          write index.ts
//   node tools/build-push.mjs --check  exit 1 if index.ts is out of date
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const LIBS = ["js/messages.js", "js/reminders.js", "js/push-logic.js"];
const TEMPLATE = "supabase/functions/push/template.ts";
const OUT = "supabase/functions/push/index.ts";
const MARKER = "/*@@INLINE@@*/";

const read = (f) => readFileSync(join(ROOT, f), "utf8");

function build() {
  const tpl = read(TEMPLATE);
  if (!tpl.includes(MARKER)) throw new Error(`${TEMPLATE} has no ${MARKER} marker`);
  const libs = LIBS.map((f) => `// ---- ${f} ----\n${read(f).trimEnd()}\n`).join("\n");
  const header = "// GENERATED by tools/build-push.mjs — do not edit. Edit template.ts or js/*.js, then run: node tools/build-push.mjs\n";
  const [first, ...rest] = tpl.split("\n");
  // keep "// @ts-nocheck" as the very first line
  return `${first}\n${header}${rest.join("\n").replace(MARKER, libs.trimEnd())}`;
}

const out = build();
const target = join(ROOT, OUT);
if (process.argv.includes("--check")) {
  if (!existsSync(target) || readFileSync(target, "utf8") !== out) {
    console.error(`${OUT} is out of date: run node tools/build-push.mjs`);
    process.exit(1);
  }
  console.log(`${OUT} is up to date`);
} else {
  writeFileSync(target, out);
  console.log(`wrote ${OUT}`);
}
